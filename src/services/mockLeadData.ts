/** Always keep temperature statuses at the front of Status dropdowns. */
export const BUILTIN_LEAD_TEMPERATURE_STATUSES = ['Hot', 'Warm', 'Cold'] as const;

export function mergeLeadStatusesWithBuiltins(statuses: string[] | undefined | null): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of [...BUILTIN_LEAD_TEMPERATURE_STATUSES, ...(statuses || [])]) {
    const value = String(item || '').trim();
    if (!value) continue;
    const key = value.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(value);
  }
  return out.length ? out : [...LEAD_STATUSES];
}

