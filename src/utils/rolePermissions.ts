export function getPermissionsForRole(role: CrmRole | string | null | undefined): readonly string[] {
  const key = String(role || '').trim().toLowerCase() as CrmRole;
  return ROLE_PERMISSION_PRESETS[key] || ROLE_PERMISSION_PRESETS['crm-employee'];
}

export function roleHasPermission(role: CrmRole | string | null | undefined, permission: string): boolean {
  const perms = getPermissionsForRole(role);
  if (perms.includes('*')) return true;
  return perms.includes(permission);
}
